"""Prepare lightweight slides once; generated WebP files are committed for hosting.

Requires Poppler (pdfinfo, pdftoppm, pdftotext) and Pillow.
Run again after replacing a source PDF or changing the rendering settings.
"""
from concurrent.futures import ThreadPoolExecutor
from hashlib import sha256
import json
from pathlib import Path
import re
import subprocess
import tempfile

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RENDER_VERSION = b"slides-webp-v1-1920-q86-960-q82-cover480-q78"
SOURCES = [
    ("1_Temas_I_y_II_IA_y_Chatbots.pdf", "IA y chatbots", "Temas I y II", "Conoce la IA y sus usos en tu negocio."),
    ("2_Tema_III_Tendencias_y_precios.pdf", "Tendencias y precios", "Tema III", "Investiga el mercado y compara precios."),
    ("3_Tema_IV_Clase_1_Contenido_para_redes.pdf", "Contenido para redes", "Tema IV · Clase 1", "Prepara publicaciones para tu negocio."),
    ("4_Tema_IV_Clase_2_Perfiles_turisticos.pdf", "Perfiles turísticos", "Tema IV · Clase 2", "Mejora la presentación de tu perfil turístico."),
    ("5_Tema_IV_Clase_3_Tu_perfil_en_vivo.pdf", "Tu perfil en vivo", "Tema IV · Clase 3", "Actualiza tu perfil paso a paso."),
    ("6_Tema_IV_Practica_integradora_Perfiles_turisticos.pdf", "Configura tus perfiles turísticos", "Tema IV · Práctica integradora", "Tu ficha maestra, Google Maps y Airbnb en una sola práctica."),
]


def render(item):
    index, (filename, title, topic, description) = item
    source = ROOT / "public/materiales" / filename
    digest = sha256(RENDER_VERSION + source.read_bytes()).hexdigest()[:16]
    output = ROOT / "public/materiales/clases" / digest
    output.mkdir(parents=True, exist_ok=True)
    info = subprocess.check_output(["pdfinfo", str(source)], text=True)
    count = int(re.search(r"Pages:\s+(\d+)", info).group(1))
    if len(list(output.glob("page-*.webp"))) != count * 2:
        with tempfile.TemporaryDirectory(prefix="aula-slides-") as temporary:
            prefix = Path(temporary) / "slide"
            subprocess.run(["pdftoppm", "-png", "-scale-to", "1920", str(source), str(prefix)], check=True)
            pages = sorted(Path(temporary).glob("slide-*.png"))
            assert len(pages) == count
            for number, path in enumerate(pages, 1):
                with Image.open(path) as image:
                    image = image.convert("RGB")
                    image.save(output / f"page-{number:03}.webp", "WEBP", quality=86, method=5)
                    small = image.copy()
                    small.thumbnail((960, 960), Image.Resampling.LANCZOS)
                    small.save(output / f"page-{number:03}-960.webp", "WEBP", quality=82, method=5)
                    if number == 1:
                        cover = image.copy()
                        cover.thumbnail((480, 480), Image.Resampling.LANCZOS)
                        cover.save(output / "cover.webp", "WEBP", quality=78, method=5)
    raw_text = subprocess.check_output(["pdftotext", str(source), "-"], text=True)
    text = [part.strip() for part in raw_text.split("\f")[:count]]
    (output / "text.json").write_text(json.dumps(text, ensure_ascii=False) + "\n")
    with Image.open(output / "page-001.webp") as image:
        width, height = image.size
    presentation = dict(id=str(index), number=index, file=filename, title=title, topic=topic,
                        description=description, pages=count, width=width, height=height,
                        assets=f"/materiales/clases/{digest}", hasText=any(text))
    total = sum(path.stat().st_size for path in output.iterdir())
    print(f"Clase {index}: {count} páginas · {total:,} bytes", flush=True)
    return presentation


if __name__ == "__main__":
    with ThreadPoolExecutor(max_workers=2) as executor:
        catalog = list(executor.map(render, enumerate(SOURCES, 1)))
    (ROOT / "public/presentations.js").write_text(
        "// Generated by scripts/render-presentations.py from the original PDFs.\n"
        + "export const presentations = " + json.dumps(catalog, ensure_ascii=False, indent=2) + ";\n")
